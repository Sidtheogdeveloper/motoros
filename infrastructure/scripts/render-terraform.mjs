import { readFileSync, writeFileSync, existsSync, renameSync } from 'node:fs';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
const schema = JSON.parse(readFileSync(process.argv[2], 'utf8').replace(/^\uFEFF/, ''));
const provider = schema.provider_schemas['registry.terraform.io/hashicorp/aws'];
const paths = [
  'infrastructure/terraform/modules/environment',
  'infrastructure/terraform/environments/staging',
  'infrastructure/terraform/environments/production',
];
function value(x) {
  if (typeof x === 'string')
    return x.startsWith('${') && x.endsWith('}') ? x.slice(2, -1) : JSON.stringify(x);
  if (Array.isArray(x)) return '[' + x.map(value).join(', ') + ']';
  if (x && typeof x === 'object')
    return (
      '{\n' +
      Object.entries(x)
        .map(([k, v]) => JSON.stringify(k) + ' = ' + value(v))
        .join('\n') +
      '\n}'
    );
  return JSON.stringify(x);
}
function body(attributes, block = {}) {
  return Object.entries(attributes)
    .map(([key, x]) => {
      if (key === '__skip') return x.map((s) => '# checkov:skip=' + s).join('\n');
      if (key === 'dynamic')
        return Object.entries(x)
          .map(
            ([n, v]) =>
              `dynamic "${n}" {\nfor_each = ${value(v.for_each)}\ncontent {\n${body(v.content, block.block_types?.[n]?.block)}\n}\n}`,
          )
          .join('\n');
      if (key === 'lifecycle')
        return `lifecycle {\n${Object.entries(x)
          .map(
            ([n, v]) => n + ' = ' + (n === 'ignore_changes' ? '[' + v.join(',') + ']' : value(v)),
          )
          .join('\n')}\n}`;
      if (key === 'depends_on') return 'depends_on = [' + x.join(',') + ']';
      if (block.block_types?.[key])
        return (Array.isArray(x) ? x : [x])
          .map((v) => `${key} {\n${body(v, block.block_types[key].block)}\n}`)
          .join('\n');
      return `${key} = ${value(x)}`;
    })
    .join('\n');
}
for (const path of paths) {
  const input = resolve(path, 'main.tfmodel.json');
  if (!existsSync(input)) renameSync(resolve(path, 'main.tf.json'), input);
  const raw = readFileSync(input, 'utf8').replace(/\r\n/g, '\n'),
    d = JSON.parse(raw);
  let output =
    '# Generated by infrastructure/scripts/render-terraform.mjs from main.tfmodel.json\n# Model SHA256: ' +
    createHash('sha256').update(raw).digest('hex') +
    '\n';
  for (const [type, items] of Object.entries(d)) {
    if (type === 'terraform') {
      output += 'terraform {\n';
      for (const [key, x] of Object.entries(items)) {
        if (key === 'required_providers') output += 'required_providers {\n' + body(x) + '\n}\n';
        else if (key === 'backend')
          output += Object.entries(x)
            .map(([k, v]) => `backend "${k}" {\n${body(v)}\n}\n`)
            .join('');
        else output += key + ' = ' + value(x) + '\n';
      }
      output += '}\n';
    } else if (type === 'locals') output += 'locals {\n' + body(items) + '\n}\n';
    else if (type === 'resource' || type === 'data')
      for (const [kind, blocks] of Object.entries(items))
        for (const [name, attrs] of Object.entries(blocks))
          output += `${type} "${kind}" "${name}" {\n${body(attrs, (type === 'resource' ? provider.resource_schemas : provider.data_source_schemas)[kind].block)}\n}\n`;
    else
      for (const [name, attrs] of Object.entries(items)) {
        const custom = {
          block_types:
            type === 'variable'
              ? { validation: { block: {} } }
              : type === 'check'
                ? { assert: { block: {} } }
                : type === 'provider'
                  ? provider.provider.block.block_types
                  : {},
        };
        const rendered =
          type === 'variable'
            ? body(
                Object.fromEntries(Object.entries(attrs).filter(([k]) => k !== 'type')),
                custom,
              ) +
              '\ntype = ' +
              attrs.type
            : body(attrs, custom);
        output += `${type} "${name}" {\n${rendered}\n}\n`;
      }
  }
  writeFileSync(resolve(path, 'main.tf'), output);
}
